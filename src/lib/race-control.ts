export function translateRaceControl(message: string, locale: string): string {
  if (locale !== "es") return message;
  const text = message.trim();
  if (EXACT[text]) return EXACT[text];
  for (const [re, out] of PATTERNS) if (re.test(text)) return text.replace(re, out);
  if (/STEWARDS|INCIDENT|PENALTY/.test(text)) return PHRASES.reduce((acc, [re, out]) => acc.replace(re, out), text);
  return text;
}
